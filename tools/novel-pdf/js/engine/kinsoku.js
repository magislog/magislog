/* ============================================================
   kinsoku.js  ―― 禁則処理の文字集合（機械）
   ここは「判定の材料」だけ。実際の追い出し／ぶら下げは typeset.js が行う。
     ・行頭禁則 … 行のアタマに来てはいけない文字（閉じ括弧・句読点・小書き仮名等）
     ・行末禁則 … 行のオシリに来てはいけない文字（開き括弧等）
     ・ぶら下げ … 行末からはみ出して置いてよい文字（、。）
   ============================================================ */
;(function () {
  'use strict';
  const RNK = (window.RNK = window.RNK || {});

  // 行頭禁則
  const START_FORBIDDEN = new Set([
    '、', '。', '，', '．', '・', '：', '；', '？', '！', '‼', '⁉', '⁈', '⁇',
    'ー', 'ゝ', 'ゞ', '々', '〻',
    'ぁ', 'ぃ', 'ぅ', 'ぇ', 'ぉ', 'っ', 'ゃ', 'ゅ', 'ょ', 'ゎ', 'ゕ', 'ゖ',
    'ァ', 'ィ', 'ゥ', 'ェ', 'ォ', 'ッ', 'ャ', 'ュ', 'ョ', 'ヮ', 'ヵ', 'ヶ', 'ヽ', 'ヾ',
    '）', ')', '｝', '}', '〕', '］', ']', '」', '』', '】', '〉', '》', '〗', '〙', '〛',
    '”', '’', '〟', '…', '‥', '‐',
  ]);

  // 行末禁則
  const END_FORBIDDEN = new Set([
    '（', '(', '｛', '{', '〔', '［', '[', '「', '『', '【', '〈', '《', '〖', '〘', '〚',
    '“', '‘', '〝',
  ]);

  // ぶら下げ可能（行末からはみ出して置ける約物）
  const HANGABLE = new Set(['、', '。', '，', '．', '､', '｡']);

  RNK.kinsoku = {
    START_FORBIDDEN, END_FORBIDDEN, HANGABLE,
    isStartForbidden: (c) => START_FORBIDDEN.has(c),
    isEndForbidden: (c) => END_FORBIDDEN.has(c),
    isHangable: (c) => HANGABLE.has(c),
  };
})();
